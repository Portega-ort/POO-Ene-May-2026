package edu.pedro.ortega.actividad2.calculadora.process;

/**
 * Clase que implementa la operación de resta.
 */
public class Resta {
    /**
     * Realiza la resta de dos números.
     *
     * @param a Minuendo.
     * @param b Sustraendo.
     * @return La diferencia entre a y b.
     */
    public static double ejecutar(double a, double b) {
        return a - b;
    }
}
